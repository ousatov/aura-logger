package com.usatov.aura.logger.demo.core.ui

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/** Shared spacing values for the demo screens. */
object Dimens {
    /** Horizontal padding of screen content. */
    val ScreenHorizontal: Dp = 16.dp

    /** Vertical padding at the top and bottom of a scrolling screen. */
    val ScreenVertical: Dp = 16.dp

    /** Gap between sibling items inside a section. */
    val ItemSpacing: Dp = 8.dp

    /** Gap between sections on one screen. */
    val SectionSpacing: Dp = 24.dp

    /** Inner padding of a card. */
    val CardPadding: Dp = 16.dp
}
